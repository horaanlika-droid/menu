export const isValidSettings = (value) =>
  value &&
  ["light", "burgundy"].includes(value.backStyle) &&
  typeof value.eventName === "string" &&
  value.eventName.length <= 45 &&
  typeof value.date === "string" &&
  value.date.length <= 30 &&
  typeof value.cropMarks === "boolean";
export function loadSavedDeck(storage) {
  try {
    const saved = JSON.parse(storage.getItem(STORAGE_KEY));
    if (!saved || typeof saved !== "object")
      return { edits: {}, settings: DEFAULT_SETTINGS };
    const edits = {};
    for (const original of DECK) {
      const edit = saved.edits?.[original.id];
      if (
        edit &&
        typeof edit.title === "string" &&
        edit.title.trim() &&
        edit.title.length <= 48 &&
        typeof edit.description === "string" &&
        edit.description.trim() &&
        edit.description.length <= 170
      ) {
        edits[original.id] = {
          title: edit.title,
          description: edit.description,
        };
      }
    }
    return {
      edits,
      settings: isValidSettings(saved.settings)
        ? saved.settings
        : DEFAULT_SETTINGS,
    };
  } catch {
    return { edits: {}, settings: DEFAULT_SETTINGS };
  }
}
